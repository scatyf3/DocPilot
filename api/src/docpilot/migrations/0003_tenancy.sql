-- Tenants and user accounts. Every library row now belongs to a tenant.
--
-- Rows that existed before this migration go to tenant 1, "default", which is also the tenant
-- service API keys act on. Each tenant_id column gets a temporary DEFAULT 1 only to backfill
-- (a constant default is a metadata change, not a table rewrite), then loses it: a write that
-- forgets its tenant must fail, not land in tenant 1.

CREATE TABLE tenants (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
INSERT INTO tenants (id, name) VALUES (1, 'default');
SELECT setval(pg_get_serial_sequence('tenants', 'id'), 1);

CREATE TABLE users (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id      bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    email          text NOT NULL,
    password_hash  text NOT NULL,                -- argon2id, PHC string format
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_idx ON users (lower(email));

-- Opaque refresh tokens, stored as SHA-256 hashes. Each one is single-use: refreshing marks it
-- used and issues the next one in the same family. Presenting a used token again means it was
-- stolen (or replayed), so the whole family is revoked.
CREATE TABLE refresh_tokens (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    family_id   uuid NOT NULL,
    token_hash  bytea NOT NULL UNIQUE,
    expires_at  timestamptz NOT NULL,
    used_at     timestamptz,
    revoked_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family_id);
CREATE INDEX refresh_tokens_expiry_idx ON refresh_tokens (expires_at);

-- Documents and chunks. chunks.tenant_id duplicates its document's so retrieval can filter
-- (and row-level security can check) without a join; the composite foreign key keeps the two
-- from ever disagreeing.
ALTER TABLE documents
    ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1 REFERENCES tenants(id) ON DELETE CASCADE,
    ADD COLUMN created_by bigint REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE documents ALTER COLUMN tenant_id DROP DEFAULT;
ALTER TABLE documents ADD CONSTRAINT documents_id_tenant_key UNIQUE (id, tenant_id);
CREATE INDEX documents_tenant_idx ON documents (tenant_id, created_at DESC);

ALTER TABLE chunks ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1;
ALTER TABLE chunks ALTER COLUMN tenant_id DROP DEFAULT;
ALTER TABLE chunks DROP CONSTRAINT chunks_document_id_fkey;
ALTER TABLE chunks ADD CONSTRAINT chunks_document_tenant_fkey
    FOREIGN KEY (document_id, tenant_id) REFERENCES documents (id, tenant_id) ON DELETE CASCADE;
CREATE INDEX chunks_tenant_idx ON chunks (tenant_id);

-- Conversations: ids come from the client, so they are only unique within a tenant. Keying
-- them by (tenant_id, id) means another tenant's chat id can neither collide with nor reveal
-- one of ours. user_id is NULL for conversations held by an API key.
ALTER TABLE conversations
    ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1 REFERENCES tenants(id) ON DELETE CASCADE,
    ADD COLUMN user_id bigint REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE conversations ALTER COLUMN tenant_id DROP DEFAULT;

ALTER TABLE messages ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1;
ALTER TABLE messages ALTER COLUMN tenant_id DROP DEFAULT;
ALTER TABLE messages DROP CONSTRAINT messages_conversation_id_fkey;
ALTER TABLE conversations DROP CONSTRAINT conversations_pkey;
ALTER TABLE conversations ADD PRIMARY KEY (tenant_id, id);
ALTER TABLE messages ADD CONSTRAINT messages_conversation_fkey
    FOREIGN KEY (tenant_id, conversation_id) REFERENCES conversations (tenant_id, id) ON DELETE CASCADE;
ALTER TABLE messages ADD CONSTRAINT messages_id_tenant_key UNIQUE (id, tenant_id);
DROP INDEX messages_conversation_idx;
CREATE INDEX messages_conversation_idx ON messages (tenant_id, conversation_id, created_at);

ALTER TABLE traces ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1;
ALTER TABLE traces ALTER COLUMN tenant_id DROP DEFAULT;
ALTER TABLE traces DROP CONSTRAINT traces_message_id_fkey;
ALTER TABLE traces ADD CONSTRAINT traces_message_tenant_fkey
    FOREIGN KEY (message_id, tenant_id) REFERENCES messages (id, tenant_id) ON DELETE CASCADE;
