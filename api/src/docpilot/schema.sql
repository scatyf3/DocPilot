-- DocPilot schema. Idempotent: `docpilot db init` runs it on every deploy.
-- Tables are created in the current search_path (DB_SCHEMA), so evals can use their own namespace.

CREATE TABLE IF NOT EXISTS documents (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    title       text NOT NULL,
    source      text NOT NULL,                  -- original filename, or 'agent' for generated pages
    kind        text NOT NULL DEFAULT 'upload' CHECK (kind IN ('upload', 'generated')),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chunks (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    document_id  bigint NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    ord          int NOT NULL,                  -- position within the document
    text         text NOT NULL,
    tsv          tsvector GENERATED ALWAYS AS (to_tsvector('english', text)) STORED,
    embedding    vector(1024) NOT NULL,
    UNIQUE (document_id, ord)
);

-- Full-text side of hybrid retrieval.
CREATE INDEX IF NOT EXISTS chunks_tsv_idx ON chunks USING gin (tsv);
-- Vector side: approximate nearest neighbour over cosine distance.
CREATE INDEX IF NOT EXISTS chunks_embedding_idx ON chunks USING hnsw (embedding vector_cosine_ops);

CREATE TABLE IF NOT EXISTS conversations (
    id          text PRIMARY KEY,               -- chat id generated by the web client
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS messages (
    id               uuid PRIMARY KEY,
    conversation_id  text NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role             text NOT NULL CHECK (role IN ('user', 'assistant')),
    content          text NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS messages_conversation_idx ON messages (conversation_id, created_at);

-- One row per assistant turn: what the agent saw, did, and spent.
CREATE TABLE IF NOT EXISTS traces (
    id                   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message_id           uuid NOT NULL UNIQUE REFERENCES messages(id) ON DELETE CASCADE,
    retrieved_chunk_ids  bigint[] NOT NULL DEFAULT '{}',
    tool_calls           jsonb NOT NULL DEFAULT '[]',
    model                text NOT NULL,
    input_tokens         int NOT NULL,
    output_tokens        int NOT NULL,
    latency_ms           int NOT NULL,
    cost_usd             numeric(12, 6) NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now()
);
