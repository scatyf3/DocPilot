"""Generate schema.dot (DocPilot relational schema, vector columns omitted) and render it.

Usage: python3 make_schema.py   -> schema.{dot,svg,pdf,png}
"""
import subprocess

MONO = "Source Code Pro"
GROUPS = {
    "conv": dict(label="Conversation log", ink="#7A4B1C", fill="#F4E6D6", frame="#C9A27A"),
    "docs": dict(label="Document store", ink="#1F4E79", fill="#DCE6F2", frame="#8EA9C8"),
}
# (key, column, type, port, italic)
TABLES = {
    "conversations": ("conv", [("PK", "id", "text", "id", False),
                               ("", "created_at", "timestamptz", None, False)]),
    "messages": ("conv", [("PK", "id", "uuid", "id", False),
                          ("FK", "conversation_id", "text", "conversation_id", False),
                          ("", "role", "{user, assistant}", None, False),
                          ("", "content", "text", None, False),
                          ("", "created_at", "timestamptz", None, False)]),
    "traces": ("conv", [("PK", "id", "bigint", None, False),
                        ("FK, UQ", "message_id", "uuid", "message_id", False),
                        ("", "retrieved_chunk_ids", "bigint[]", "retrieved", True),
                        ("", "rejected_citation_ids", "bigint[]", None, True),
                        ("", "tool_calls", "jsonb", None, False),
                        ("", "model", "text", None, False),
                        ("", "input_tokens", "int", None, False),
                        ("", "output_tokens", "int", None, False),
                        ("", "latency_ms", "int", None, False),
                        ("", "cost_usd", "numeric", None, False),
                        ("", "created_at", "timestamptz", None, False)]),
    "documents": ("docs", [("PK", "id", "bigint", "id", False),
                           ("", "title", "text", None, False),
                           ("", "source", "text", None, False),
                           ("", "kind", "{upload, generated}", None, False),
                           ("", "created_at", "timestamptz", None, False)]),
    "chunks": ("docs", [("PK", "id", "bigint", "id", False),
                        ("FK", "document_id", "bigint", "document_id", False),
                        ("", "ord", "int", None, False),
                        ("", "text", "text", None, False)]),
}
NOTES = {"chunks": "UNIQUE (document_id, ord)"}


def table(name: str) -> str:
    g = GROUPS[TABLES[name][0]]
    rows = [f'<TR><TD COLSPAN="4" BGCOLOR="{g["fill"]}" ALIGN="LEFT" CELLPADDING="5">'
            f'<B>{name}</B></TD></TR>']
    for key, col, typ, port, italic in TABLES[name][1]:
        # Ports: West side on the key cell (edges arrive), East side on the type cell (edges leave),
        # so lines meet the table border instead of crossing text.
        wp = f' PORT="{port}_w"' if port else ""
        ep = f' PORT="{port}_e"' if port else ""
        k = f'<FONT POINT-SIZE="8" COLOR="{g["ink"]}"><B>{key}</B></FONT>' if key else ""
        c = f"<U>{col}</U>" if key.startswith("PK") else (f"<I>{col}</I>" if italic else col)
        t = f'<FONT FACE="{MONO}" POINT-SIZE="8.5" COLOR="#6B6B6B">{typ}</FONT>'
        rows.append(f'<TR><TD ALIGN="LEFT"{wp}>{k}</TD><TD ALIGN="LEFT">{c}</TD>'
                    f'<TD ALIGN="LEFT"{ep}>{t}</TD><TD WIDTH="4"></TD></TR>')
    if name in NOTES:
        rows.append(f'<TR><TD></TD><TD COLSPAN="3" ALIGN="LEFT"><FONT POINT-SIZE="8" COLOR="#8A8A8A">'
                    f'<I>{NOTES[name]}</I></FONT></TD></TR>')
    body = "\n    ".join(rows)
    return (f'  {name} [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="2.5" '
            f'COLOR="{g["ink"]}">\n    {body}\n  </TABLE>>];')


def cluster(gid: str) -> str:
    g = GROUPS[gid]
    members = "\n".join(table(t) for t, (grp, _) in TABLES.items() if grp == gid)
    return (f'subgraph cluster_{gid} {{\n'
            f'  label=<<B>{g["label"]}</B>>; labeljust=l; fontcolor="{g["ink"]}";\n'
            f'  style="rounded,dashed"; color="{g["frame"]}"; penwidth=0.9; margin=14;\n'
            f'{members}\n}}')


ONE = "teetee"
dot = f"""// Generated by make_schema.py. DocPilot relational schema; vector columns and indexes omitted.
digraph schema {{
graph [rankdir=LR, fontname="Nimbus Sans", fontsize=11, nodesep=0.45, ranksep=0.75,
       pad=0.1, newrank=true, splines=spline];
node  [shape=plaintext, fontname="Nimbus Sans", fontsize=10, margin=0];
edge  [fontname="Nimbus Sans", fontsize=8.5, color="#3C3C3C", penwidth=0.9, arrowsize=0.75, dir=both];

{cluster("conv")}

{cluster("docs")}


legend [shape=plaintext, label=<<TABLE BORDER="0" CELLBORDER="0" CELLSPACING="0" CELLPADDING="2">
  <TR><TD ALIGN="LEFT"><FONT POINT-SIZE="9" COLOR="#3C3C3C"><B>Edges</B>&#160;(crow&#39;s-foot cardinality)</FONT></TD></TR>
  <TR><TD ALIGN="LEFT"><FONT POINT-SIZE="9" COLOR="#3C3C3C">solid: foreign key, ON DELETE CASCADE</FONT></TD></TR>
  <TR><TD ALIGN="LEFT"><FONT POINT-SIZE="9" COLOR="#3C3C3C">dashed: id array, no foreign key</FONT></TD></TR>
  <TR><TD ALIGN="LEFT"><FONT POINT-SIZE="9" COLOR="#3C3C3C"><I>italic</I>&#160;columns hold such arrays</FONT></TD></TR>
</TABLE>>];
{{rank=same; conversations; legend}}
{{rank=same; messages; documents}}
{{rank=same; traces; chunks}}

// Crow's foot: tee = one, crow = many, odot = optional.
conversations:id_e:e -> messages:conversation_id_w:w [arrowtail={ONE}, arrowhead=crowodot];
messages:id_e:e      -> traces:message_id_w:w        [arrowtail={ONE}, arrowhead=teeodot];
documents:id_e:e     -> chunks:document_id_w:w       [arrowtail={ONE}, arrowhead=crowodot];

// Soft reference: an array of ids, not enforced by a foreign key.
traces:retrieved_e:e -> chunks:id_e:e [dir=forward, style=dashed, color="#8A8A8A", arrowhead=vee,
    arrowsize=0.6, constraint=false];
}}
"""

open("schema.dot", "w").write(dot)
subprocess.run(["dot", "-Tsvg", "schema.dot", "-o", "schema.svg"], check=True)
subprocess.run(["dot", "-Tpdf", "schema.dot", "-o", "schema.pdf"], check=True)
subprocess.run(["rsvg-convert", "-z", "3", "-b", "white", "schema.svg", "-o", "schema.png"], check=True)
